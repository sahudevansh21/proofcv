// 5. Timeline: dates in a narrow left column with a coloured marker, serif body, coloured headings.
function timeline(m) {
  const entry = (e) =>
    `\\entry{${texText(e.date)}}{${[
      e.title ? `\\textbf{${texText(e.title)}}` : '',
      e.subtitle ? `\\textit{${texText(e.subtitle)}}` : '',
    ]
      .filter(Boolean)
      .join('\\\\ ')}${e.bullets.length ? `\\vspace{-2pt}\n${bullets(e.bullets, 'leftmargin=1em, itemsep=0pt, topsep=2pt, parsep=0pt')}` : ''}}\n`;
  const list = (items) => items.map((t) => `\\entry{}{${texText(t)}}\n`).join('');
  return `${HEADER('Timeline')}\\documentclass[10pt,a4paper]{article}
\\usepackage[margin=1.7cm]{geometry}
${COMMON_PACKAGES}\\usepackage{newpxtext}
\\definecolor{accent}{HTML}{8A1538}
\\definecolor{muted}{HTML}{5F5F66}
\\newcommand{\\cvsection}[1]{\\par\\vspace{10pt}{\\color{accent}\\Large #1}\\\\[-5pt]\\textcolor{accent!35}{\\rule{\\linewidth}{0.8pt}}\\\\[3pt]}
\\newcommand{\\entry}[2]{\\noindent\\parbox[t]{2.9cm}{\\raggedright\\footnotesize\\color{muted}#1}\\hspace{0.2cm}\\textcolor{accent}{\\rule[0.15ex]{4pt}{4pt}}\\hspace{0.3cm}\\parbox[t]{\\dimexpr\\linewidth-3.65cm\\relax}{#2}\\par\\vspace{4pt}}

\\begin{document}
{\\fontsize{24}{28}\\selectfont ${texText(m.name)}}\\\\[2pt]
${m.headline ? `{\\large\\itshape ${texText(m.headline)}}\\\\[2pt]\n` : ''}{\\small\\color{muted} ${m.contact.map(texContact).join(' \\enspace\\textbullet\\enspace ')}}

${m.sections
  .map((s) => {
    const body =
      s.kind === 'skills'
        ? s.items.map((g) => `\\entry{${texText(g.group)}}{${g.values.map(texText).join(', ')}}\n`).join('')
        : s.kind === 'text'
          ? `\\entry{}{${texText(s.text)}}\n`
          : s.kind === 'list'
            ? list(s.items)
            : s.entries.map(entry).join('');
    return `\\cvsection{${texText(s.title)}}\n${body}`;
  })
  .join('\n')}
\\end{document}
`;
}

