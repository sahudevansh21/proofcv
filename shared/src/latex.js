// LaTeX output for ProofCV's resume templates. Every template is an original design that compiles
// with pdfLaTeX on a standard TeX Live (Overleaf's default) using only common packages.
// Content is never changed: text is escaped, and [placeholders] are kept and shown in red.

import { parseResume } from './resumeModel.js';

const UNICODE = [
  [/→/g, '$\\rightarrow$'],
  [/←/g, '$\\leftarrow$'],
  [/×/g, '$\\times$'],
  [/≥/g, '$\\geq$'],
  [/≤/g, '$\\leq$'],
  [/—/g, '---'],
  [/–/g, '--'],
  [/[‘’]/g, "'"],
  [/“/g, '``'],
  [/”/g, "''"],
  [/…/g, '\\ldots{}'],
  [/·/g, '\\textperiodcentered{}'],
  [/[•▪◦●‣]/g, '\\textbullet{}'],
  [/₹/g, 'Rs.~'],
  [/€/g, 'EUR~'],
  [/£/g, '\\pounds{}'],
  [/°/g, '\\textdegree{}'],
  [/\u00a0/g, '~'],
];

/** Escapes text for LaTeX body copy. Characters pdfLaTeX can't typeset (emoji, scripts) are dropped. */
export function escapeTex(input) {
  let s = String(input ?? '').replace(/[\\{}&%$#_~^]/g, (c) =>
    c === '\\'
      ? '\\textbackslash{}'
      : c === '~'
        ? '\\textasciitilde{}'
        : c === '^'
          ? '\\textasciicircum{}'
          : `\\${c}`,
  );
  // Restore the math and command sequences we insert below by applying them after escaping.
  for (const [re, out] of UNICODE) s = s.replace(re, out);
  // Keep Latin-1 and Latin Extended-A (T1 + utf8 handle them); drop everything else.
  return s.replace(/[^\x09\x0a\x20-\x7e\u00a0-\u017f]/g, '');
}

/** Escaped text with [placeholders] wrapped in \ph{} so they print in red until filled. */
export function texText(input) {
  return String(input ?? '')
    .split(/(\[[^\]\n]{1,40}\])/)
    .map((part) => (/^\[[^\]]+\]$/.test(part) ? `\\ph{${escapeTex(part.slice(1, -1))}}` : escapeTex(part)))
    .join('');
}

function hrefFor(contact) {
  const c = contact.trim();
  if (/^[^@\s]+@[^@\s]+\.[a-z]{2,}$/i.test(c)) return `mailto:${c}`;
  if (/^\+?[\d\s()-]{8,}$/.test(c)) return `tel:${c.replace(/[^\d+]/g, '')}`;
  if (/^(https?:\/\/)?(www\.)?[\w-]+(\.[\w-]+)+(\/\S*)?$/i.test(c)) return /^https?:/i.test(c) ? c : `https://${c}`;
  return null;
}

/** A contact item as a clickable link where it is one. */
export function texContact(contact) {
  const url = hrefFor(contact);
  const label = escapeTex(contact.replace(/^https?:\/\//i, ''));
  if (!url) return label;
  const safeUrl = url.replace(/[\\{}]/g, '').replace(/([#%])/g, '\\$1');
  return `\\href{${safeUrl}}{${label}}`;
}

const HEADER = (name) => `% Resume generated by ProofCV with the "${name}" template.
% Compile with pdfLaTeX (on Overleaf: Menu > Compiler > pdfLaTeX).
% Anything in red like [N] is a gap for a real number or fact. Fill it in or delete it before you send this.
`;

const COMMON_PACKAGES = `\\usepackage[T1]{fontenc}
\\usepackage[utf8]{inputenc}
\\usepackage{xcolor}
\\usepackage{enumitem}
\\usepackage[hidelinks]{hyperref}
\\usepackage{textcomp}
\\pagestyle{empty}
\\setlength{\\parindent}{0pt}
\\newcommand{\\ph}[1]{\\textcolor{red}{\\textbf{[#1]}}}
`;

const bullets = (items, opts = 'leftmargin=1.1em, itemsep=1pt, topsep=2pt, parsep=0pt, partopsep=0pt') =>
  items.length ? `\\begin{itemize}[${opts}]\n${items.map((b) => `  \\item{} ${texText(b)}`).join('\n')}\n\\end{itemize}\n` : '';

const skillLines = (section, sep = ', ') =>
  section.items.map((g) => (g.group ? `\\textbf{${texText(g.group)}:} ` : '') + g.values.map(texText).join(sep));

/** Splits sections into main (entries / text) and side (skills / short lists) for two-column layouts. */
function splitSections(model) {
  const side = model.sections.filter((s) => s.kind === 'skills' || s.kind === 'list');
  const main = model.sections.filter((s) => !side.includes(s));
  return { main, side };
}

/** Renders a section in a generic way; templates pass their own entry formatter. */
function sectionBody(s, entry, list = (items) => bullets(items)) {
  if (s.kind === 'skills') return `${skillLines(s).join('\\\\\n')}\n`;
  if (s.kind === 'text') return `${texText(s.text)}\n`;
  if (s.kind === 'list') return list(s.items);
  return s.entries.map((e) => endLines(entry(e))).join('\\vspace{4pt}\n');
}

/** A line break right before a list or at the end of an entry leaves an empty line; end the paragraph instead. */
const endLines = (tex) => tex.replace(/\\\\(?:\[[^\]]*\])?\n(?=\\begin\{itemize\}|$)/g, '\\par\n');

// ---------------------------------------------------------------------------------------------
// 1. Classic: single column, centred name, small-caps headings with a rule. Plain and ATS-friendly.
function classic(m) {
  const entry = (e) =>
    `${e.title ? `\\textbf{${texText(e.title)}}` : ''}${e.date ? ` \\hfill ${texText(e.date)}` : ''}${e.title || e.date ? '\\\\\n' : ''}${
      e.subtitle ? `\\textit{${texText(e.subtitle)}}\\\\\n` : ''
    }${bullets(e.bullets)}`;
  return `${HEADER('Classic')}\\documentclass[11pt,a4paper]{article}
\\usepackage[margin=1.8cm]{geometry}
${COMMON_PACKAGES}\\usepackage{charter}
\\usepackage{titlesec}
\\titleformat{\\section}{\\large\\scshape\\raggedright}{}{0em}{}[\\vspace{-2pt}\\titlerule]
\\titlespacing*{\\section}{0pt}{10pt}{6pt}

\\begin{document}

\\begin{center}
  {\\Huge\\scshape ${texText(m.name)}}\\\\[4pt]
${m.headline ? `  {\\large ${texText(m.headline)}}\\\\[3pt]\n` : ''}  ${m.contact.map(texContact).join(' \\enspace$|$\\enspace ')}
\\end{center}

${m.sections.map((s) => `\\section{${texText(s.title)}}\n${sectionBody(s, entry)}`).join('\n')}
\\end{document}
`;
}

// ---------------------------------------------------------------------------------------------
// 2. Navy Sidebar: a dark full-height band on the left with contact, skills and lists.
function sidebar(m) {
  const { main, side } = splitSections(m);
  const entry = (e) =>
    `${e.title ? `{\\bfseries ${texText(e.title)}}\\\\\n` : ''}${
      e.subtitle || e.date ? `{\\small\\color{muted}${[e.subtitle, e.date].filter(Boolean).map(texText).join(' \\textbar{} ')}}\\\\\n` : ''
    }${bullets(e.bullets, 'leftmargin=1em, itemsep=1pt, topsep=2pt, parsep=0pt, label=\\textbullet')}`;
  const sideBlock = (s) =>
    `\\sidehead{${texText(s.title)}}\n${
      s.kind === 'skills'
        ? s.items
            .map((g) => `${g.group ? `{\\bfseries ${texText(g.group)}}\\\\\n` : ''}${g.values.map((v) => `$\\circ$\\enspace ${texText(v)}`).join('\\\\\n')}`)
            .join('\\\\[4pt]\n')
        : s.items.map((v) => `$\\circ$\\enspace ${texText(v)}`).join('\\\\[2pt]\n')
    }\n`;
  return `${HEADER('Navy Sidebar')}\\documentclass[10pt,a4paper]{article}
\\usepackage[left=1.1cm,right=1.4cm,top=1.4cm,bottom=1.4cm]{geometry}
${COMMON_PACKAGES}\\usepackage[default]{sourcesanspro}
\\usepackage{paracol}
\\usepackage{eso-pic}
\\definecolor{side}{HTML}{0B1B3A}
\\definecolor{muted}{HTML}{5B6475}
\\definecolor{rule}{HTML}{0B1B3A}
\\columnratio{0.3}
\\setlength{\\columnsep}{1.5cm}
\\newlength{\\bandwidth}
\\AtBeginDocument{\\setlength{\\bandwidth}{\\dimexpr 1.1cm + 0.3\\textwidth - 0.3\\columnsep + 0.75cm\\relax}}
\\AddToShipoutPictureBG{\\AtPageLowerLeft{\\color{side}\\rule{\\bandwidth}{\\paperheight}}}
\\newcommand{\\sidehead}[1]{\\par\\vspace{10pt}{\\large #1}\\\\[-6pt]\\textcolor{white!60!side}{\\rule{\\linewidth}{0.5pt}}\\\\[2pt]}
\\newcommand{\\mainhead}[1]{\\par\\vspace{10pt}{\\large #1}\\\\[-7pt]\\textcolor{rule}{\\rule{\\linewidth}{0.6pt}}\\\\[3pt]}

\\begin{document}
\\begin{paracol}{2}
\\color{white}\\raggedright
\\sidehead{Personal info}
${m.contact.map(texContact).join('\\\\[2pt]\n')}
${side.map(sideBlock).join('')}
\\switchcolumn
\\color{black}
{\\fontsize{26}{30}\\selectfont ${texText(m.name)}}\\\\[2pt]
${m.headline ? `{\\large\\color{muted} ${texText(m.headline)}}\\\\\n` : ''}
${main.map((s) => `\\mainhead{${texText(s.title)}}\n${sectionBody(s, entry)}`).join('\n')}
\\end{paracol}
\\end{document}
`;
}

// ---------------------------------------------------------------------------------------------
// 3. Accent Columns: bold name, coloured headings with a thick rule, main + side columns, skill tags.
function accent(m) {
  const { main, side } = splitSections(m);
  const entry = (e) =>
    `${e.title ? `{\\large ${texText(e.title)}}\\\\\n` : ''}${
      e.subtitle ? `{\\color{accent}\\bfseries ${texText(e.subtitle)}}\\\\\n` : ''
    }${e.date ? `{\\small\\color{muted}${texText(e.date)}}\\\\\n` : ''}${bullets(e.bullets, 'leftmargin=1em, itemsep=1pt, topsep=2pt, parsep=0pt, label={\\color{accent}\\textbullet}')}`;
  const sideBlock = (s) =>
    `\\cvsection{${texText(s.title)}}\n${
      s.kind === 'skills'
        ? `${s.items
            .map((g) => `${g.group ? `{\\bfseries ${texText(g.group)}}\\\\[2pt]\n` : ''}${g.values.map((v) => `\\cvtag{${texText(v)}}`).join('\n')}`)
            .join('\\\\[4pt]\n')}\n`
        : bullets(s.items, 'leftmargin=1em, itemsep=2pt, topsep=2pt, parsep=0pt, label={\\color{accent}\\textbullet}')
    }`;
  return `${HEADER('Accent Columns')}\\documentclass[10pt,a4paper]{article}
\\usepackage[margin=1.4cm]{geometry}
${COMMON_PACKAGES}\\usepackage[default]{lato}
\\usepackage{paracol}
\\definecolor{accent}{HTML}{8F1D2C}
\\definecolor{heading}{HTML}{1F1B2E}
\\definecolor{muted}{HTML}{6B6B76}
\\columnratio{0.62}
\\setlength{\\columnsep}{0.9cm}
\\newcommand{\\cvsection}[1]{\\par\\vspace{9pt}{\\color{heading}\\Large\\bfseries\\MakeUppercase{#1}}\\\\[-6pt]{\\color{accent!60}\\rule{\\linewidth}{1.6pt}}\\\\[3pt]}
\\newcommand{\\cvtag}[1]{\\fcolorbox{muted!50}{white}{\\strut\\small #1}\\hspace{2pt}\\allowbreak}
\\setlength{\\fboxsep}{2.5pt}

\\begin{document}
{\\fontsize{28}{32}\\selectfont\\bfseries\\MakeUppercase{${texText(m.name)}}}\\\\[3pt]
${m.headline ? `{\\large\\color{accent} ${texText(m.headline)}}\\\\[3pt]\n` : ''}{\\small ${m.contact.map(texContact).join(' \\quad ')}}
\\vspace{4pt}
\\begin{paracol}{2}
${main.map((s) => `\\cvsection{${texText(s.title)}}\n${sectionBody(s, entry)}`).join('\n')}
\\switchcolumn
${side.map(sideBlock).join('\n')}
\\end{paracol}
\\end{document}
`;
}

