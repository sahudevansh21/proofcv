// 6. Compact: dense one-pager, name left and contact right, blue small-caps headings, skills table.
function compact(m) {
  const entry = (e) =>
    `${e.title || e.date ? `\\textbf{${texText(e.title)}} \\hfill {\\small ${texText(e.date)}}\\\\\n` : ''}${
      e.subtitle ? `{\\small\\itshape ${texText(e.subtitle)}}\\\\[-2pt]\n` : ''
    }${bullets(e.bullets, 'leftmargin=1.2em, itemsep=0pt, topsep=1pt, parsep=0pt')}`;
  const skills = (s) =>
    `\\begin{tabular}{@{}l@{\\hspace{6pt}:\\hspace{6pt}}p{0.78\\linewidth}@{}}\n${s.items
      .map((g) => `\\textbf{${texText(g.group || s.title)}} & ${g.values.map(texText).join(', ')}\\\\`)
      .join('\n')}\n\\end{tabular}\n`;
  return `${HEADER('Compact')}\\documentclass[10pt,a4paper]{article}
\\usepackage[margin=1.3cm]{geometry}
${COMMON_PACKAGES}\\usepackage{helvet}
\\renewcommand{\\familydefault}{\\sfdefault}
\\usepackage{titlesec}
\\definecolor{accent}{HTML}{1F4E9A}
\\titleformat{\\section}{\\color{accent}\\scshape\\large}{}{0em}{}[\\vspace{-1pt}{\\color{black!60}\\titlerule}]
\\titlespacing*{\\section}{0pt}{8pt}{4pt}

\\begin{document}
\\begin{tabular*}{\\linewidth}{@{}l@{\\extracolsep{\\fill}}r@{}}
  {\\LARGE\\bfseries ${texText(m.name)}} & {\\small ${m.contact.slice(0, 2).map(texContact).join(' \\textbar{} ')}}\\\\
  ${m.headline ? `{\\color{accent}\\scshape ${texText(m.headline)}}` : ''} & {\\small ${m.contact.slice(2).map(texContact).join(' \\textbar{} ')}}\\\\
\\end{tabular*}

${m.sections
  .map((s) => `\\section{${texText(s.title)}}\n${s.kind === 'skills' ? skills(s) : sectionBody(s, entry)}`)
  .join('\n')}
\\end{document}
`;
}

