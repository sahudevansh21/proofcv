/** Upper-cased, letter-spaced text that works on every TeX engine (no microtype letterspacing). */
function spaced(text, gap) {
  return [...String(text).toUpperCase()]
    .map((ch) => (ch === ' ' ? `\\hspace{${gap}}\\ \\hspace{${gap}}` : escapeTex(ch)))
    .join(`\\hspace{${gap}}`);
}

// 4. Margin Notes: spaced-out name, section labels sit in a wide left margin, thin rules.
function margin(m) {
  const entry = (e) =>
    `${e.title ? `{\\bfseries\\MakeUppercase{${texText(e.title)}}}` : ''}${e.date ? `\\hfill{\\color{accent}${texText(e.date)}}` : ''}${e.title || e.date ? '\\\\\n' : ''}${
      e.subtitle ? `{\\itshape\\color{accent}${texText(e.subtitle)}}\\\\\n` : ''
    }${bullets(e.bullets, 'leftmargin=1em, itemsep=1pt, topsep=2pt, parsep=0pt, label={\\color{muted}\\textbullet}')}`;
  const contactRows = m.contact.map((c) => {
    const kind = /@/.test(c) ? 'E-mail' : /^\+?[\d\s()-]{8,}$/.test(c) ? 'Phone' : /linkedin/i.test(c) ? 'LinkedIn' : /github/i.test(c) ? 'GitHub' : 'Web';
    return `\\textbf{${kind}} & \\textcolor{muted}{${texContact(c)}}\\\\`;
  });
  return `${HEADER('Margin Notes')}\\documentclass[10pt,a4paper]{article}
\\usepackage[left=5.2cm,right=1.8cm,top=2cm,bottom=1.8cm,marginparwidth=3.4cm,marginparsep=0.6cm]{geometry}
${COMMON_PACKAGES}\\usepackage[sfdefault,light]{roboto}
\\usepackage{tabularx}
\\definecolor{accent}{HTML}{6E7FA3}
\\definecolor{muted}{HTML}{7A7A84}
\\reversemarginpar
\\newcommand{\\cvsection}[1]{\\par\\vspace{12pt}\\noindent\\textcolor{black!70}{\\rule{\\linewidth}{0.5pt}}\\marginpar{\\raggedleft\\vspace{-8pt}\\small\\bfseries #1}\\\\[4pt]}

\\begin{document}
\\noindent\\rule{0.6pt}{20pt}\\\\
{\\LARGE ${spaced(m.name, '0.22em')}}\\\\[2pt]
${m.headline ? `{${spaced(m.headline, '0.08em')}}\\\\\n` : ''}\\rule{0.6pt}{20pt}

${m.contact.length ? `\\cvsection{${spaced('Contact info', '0.12em')}}\n\\begin{tabularx}{\\linewidth}{@{}p{2.2cm}X@{}}\n${contactRows.join('\n')}\n\\end{tabularx}\n` : ''}
${m.sections.map((s) => `\\cvsection{${spaced(s.title, '0.12em')}}\n${sectionBody(s, entry)}`).join('\n')}
\\end{document}
`;
}

