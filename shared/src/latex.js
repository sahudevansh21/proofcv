/** Builds a complete .tex file for a resume (plain text) in the chosen template. */
export function resumeToLatex(resumeText, templateId) {
  const template = TEMPLATES.find((t) => t.id === templateId) ?? TEMPLATES[0];
  return template.toTex(parseResume(resumeText));
}
